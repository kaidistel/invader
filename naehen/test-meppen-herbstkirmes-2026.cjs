const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=__dirname;
const source=fs.readFileSync(path.join(root,"meppen-herbstkirmes-2026-config.js"),"utf8");
const sandbox={window:{}};vm.runInNewContext(source,sandbox);
const event=sandbox.window.NAEHEN_MEPPEN_HERBSTKIRMES_2026;
assert.ok(event,"Meppen config must expose the expected global");
assert.equal(event.park.slug,"meppen-herbstkirmes-2026");
assert.equal(event.park.kind,"fair");
assert.equal(event.park.startDate,"2026-10-16");
assert.equal(event.park.endDate,"2026-10-19");
assert.equal(event.park.specialMap,undefined,"no map requested");
assert.equal(event.park.liveWaits,false);
assert.equal(event.rides.length,6);
assert.equal(new Set(Array.from(event.rides,r=>r.id)).size,6);
const expected=[["AS Speed Drive XXL","Braun"],["Musik Express","Ahrend/Noack"],["Extrem","Karabeg"],["Projekt 1","Freiwald"],["Super Dance","Braun"],["Crazy Machine","Ahrend"]];
event.rides.forEach((r,i)=>{assert.equal(r.name,expected[i][0]);assert.equal(r.operator,expected[i][1]);assert.equal(r.priceEuro,null);assert.ok(event.worlds[r.id]);assert.ok(event.fonts[r.id]);});
assert.ok(event.rides[1].imageUrl.includes("musikexpress-noack"));
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const sw=fs.readFileSync(path.join(root,"sw.js"),"utf8");
assert.ok(html.includes('meppen-herbstkirmes-2026-config.js?v=125'));
assert.ok(app.includes("window.NAEHEN_MEPPEN_HERBSTKIRMES_2026"));
assert.ok(sw.includes("naehen-v125")&&sw.includes("./meppen-herbstkirmes-2026-config.js"));
console.log("PASS Meppen: event registered, six rides, Ahrend-Noack photo, no map, version 119");
