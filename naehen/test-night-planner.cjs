// Night Ride Planner regression checks. Run: node naehen/test-night-planner.cjs
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const core = require("./night-planner-core.js");
const root = __dirname;
const html = fs.readFileSync(path.join(root,"index.html"),"utf8");
const app = fs.readFileSync(path.join(root,"app.js"),"utf8");
const sw = fs.readFileSync(path.join(root,"sw.js"),"utf8");
const ui = fs.readFileSync(path.join(root,"night-planner.js"),"utf8");
const css = fs.readFileSync(path.join(root,"night-planner.css"),"utf8");
const ride = (opts={}) => ({ id:"taron",name:"Taron",kind:"ride",zone:"Mystery",selected:true,hasLive:true,isOpen:true,wait:35,minutes:5,order:0,...opts });
const show = (id,time,zone,minutes,buffer) => ({id,name:id,kind:"show",zone,selected:true,time,minutes,buffer});
const base = {date:"2026-11-16",start:"17:00",end:"20:00",walkMinutes:8,
 entries:[show("kaiser","17:30","Berlin",10,10),ride(),show("tiempo","18:55","Mexico",25,15),show("magic","19:50","Berlin",10,15)]};
const scheduled=core.buildSchedule(base);
assert(scheduled.valid);
assert.deepEqual(scheduled.steps.map(s=>s.id),["kaiser","taron","tiempo","magic"]);
assert(scheduled.steps.every(s=>s.end <= 1200));
assert.equal(core.walking("Berlin","Berlin",8),5);
assert.equal(core.walking("Berlin","Mexico",8),8);
assert.equal(core.parseTime("25:30"),null);
assert.equal(core.asTime(1190),"19:50");
assert.equal(core.buildSchedule({...base,entries:[show("tiempo","","Mexico",25,15)]}).unplanned[0].reason,"Tagesaktuelle Showzeit bitte eintragen");
assert.equal(core.buildSchedule({...base,date:"2026-12-24"}).valid,false);
assert.equal(core.buildSchedule({...base,date:"2026-12-31"}).valid,false);
assert.equal(core.buildSchedule({...base,isToday:true,entries:[ride({isOpen:false})]}).steps.length,0);
assert.equal(core.buildSchedule({...base,entries:[ride({useQuickPass:true,quickWait:10})]}).steps[0].end,1035);
assert.equal(core.buildSchedule({...base,entries:[ride({wait:190})]}).unplanned.length,1);
assert.equal(core.buildSchedule({...base,entries:[show("magic","19:50","Berlin",10,15)],isToday:true,nowMinutes:1190}).unplanned.length,1);
for(const id of ["nightPlanner","nightPlannerSheet","nightPlannerChoices","nightPlannerResult","nightPlannerPreview","rideQuickPass"])assert(html.includes('id="'+id+'"'),"Missing HTML ID "+id);
for(const file of ["night-planner-core.js","night-planner.js"])assert(html.includes(file+"?v=161"),"Missing asset "+file);
assert(html.includes("night-planner.css?v=182"),"Missing updated winter stylesheet");
assert(app.includes("NAEHEN_NIGHT_PLANNER?.init"),"App init missing");
assert(app.includes("refreshNightPlanner();"),"Live update missing");
assert(app.includes("ice[\\s-]*skate"),"Skate hire not filtered");
assert(sw.includes("naehen-v186")&&sw.includes("'./night-planner-core.js'"),"Old cache");
assert(ui.includes("data-npr-quick")&&ui.includes("data-npr-showtime"),"Missing planner inputs");
assert(css.includes(".npr-option-grid")&&css.includes(".wintertraumLead"),"Missing planner styles");
console.log("PASS Night Ride Planner: scheduled shows, queue, walking, Quick Pass, closures, inputs, cache");
